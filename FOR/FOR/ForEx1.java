/*
 * Propósito: Demonstrar a estrutura básica de um laço 'for' executando 100 repetições.
 */

public class ForEx1 {
    public static void main(String[] args) {
        // Laço de repetição que executa 100 vezes (de i = 1 até i = 100)
        for (int i = 1; i <= 100; i++) {
            // Imprime a mensagem "numeros1" exatamente 100 vezes no console
            System.out.println("numeros" + 1);
        }
    }
}