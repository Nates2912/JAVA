package COMECO.IntroducaoEx;

public class Variavel2 {

    public static void main(String[] args) {
        
        String nome = "Anderson";
        int idade = 25;
        float altura = 1.80f; //quanto a variavel e float, sempre coloque f no final!
        double nota = 8.5;
        char sexo = 'M'; //use ' ' quando for char!

        //concatenação, agrupar, juntar
        System.out.println("Olá "+nome+"! sua idade é: "+idade+", sua altura: "+altura+", nota: "+nota+", você é do sexo: "+sexo);

    }
}
